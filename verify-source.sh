#!/bin/bash
set -euo pipefail
echo "**************************************************"
echo "**************************************************"
echo "**************************************************"
PROJECT_DIR="$(cd "$(dirname "$0")" && pwd)"
MAIN="$PROJECT_DIR/app/src/main/java/com/kinotv/app/MainActivity.java"
ADBLOCK="$PROJECT_DIR/app/src/main/java/com/kinotv/app/AdBlocker.java"
MANUAL="$PROJECT_DIR/app/src/main/java/com/kinotv/app/AdRemovalStore.java"
RULES="$PROJECT_DIR/app/src/main/java/com/kinotv/app/PlayerUrlRules.java"
HOST="$PROJECT_DIR/app/src/main/java/com/kinotv/app/PlayerHost.java"
GRADLE="$PROJECT_DIR/app/build.gradle"
fail(){ echo "ПРОВЕРКА НЕ ПРОЙДЕНА: $*" >&2; exit 1; }
grep -q 'versionCode 94' "$GRADLE" || fail "ожидался versionCode 94"
grep -q "versionName '13.21'" "$GRADLE" || fail "ожидался versionName 13.21"
grep -q 'Conservative advertising filter for 13.0' "$ADBLOCK" || fail "не найден ad filter 13.0"
grep -q 'AD_POST_PLAYBACK_SUPPRESS_ON' "$ADBLOCK" || fail "нет post-playback ad suppress"
grep -q 'AD_RESUME_SUPPRESS' "$ADBLOCK" || fail "нет resume ad suppress"
grep -q 'activateAdPickerRuntime' "$MAIN" || fail "нет runtime popup scan для «Убрать рекламу»"
grep -q 'PICKER_FULLSCREEN_OVERLAY disabled-13.13' "$MAIN" || fail "fullscreen touch overlay должен быть отключён"
if grep -q 'setAdPickOverlayEnabled' "$HOST" "$MAIN"; then fail "вернулся touch-stealing fullscreen pick overlay"; fi
grep -q 'AD_RESUME_DOM_HIDE' "$MAIN" || fail "нет DOM hide после pause/resume"
grep -q 'AUTO_AD_HIDDEN' "$MAIN" || fail "нет автоскрытия известных popup/banner"
grep -q 'PLAYER_VIEWPORT_RESTORE' "$MAIN" || fail "нет восстановления viewport после удаления рекламы"
grep -q 'traffaret|adriver' "$MAIN" || fail "auto-hide не знает traffaret/adriver"
grep -q 'adsSuppressSticky' "$MAIN" || fail "нет sticky suppress после refresh"
grep -q 'AD_POST_PLAYBACK_SUPPRESS_KEEP' "$MAIN" || fail "нет KEEP suppress на page-start"
grep -q 'page-finished-2500' "$MAIN" || fail "нет повторного scan picker после refresh"
grep -q '__sidi_picker_hits_1314' "$MAIN" || fail "нет localized hit-catchers для iframe-баннеров"
grep -q 'adPickerPollRunnable' "$MAIN" || fail "нет poll жёлтой рамки в режиме удаления"
grep -q 'hit-click' "$MAIN" || fail "нет hit-click propose path"
grep -q 'no-auto-propose' "$MAIN" || fail "auto-propose должен быть выключен"
grep -q 'AD_RULE_SANITIZE_DROP' "$MANUAL" || fail "нет sanitize опасных player rules"
grep -q 'mTTEi' "$MANUAL" || fail "нет approved learned rule mTTEi"
grep -q 'VIDEO_AD_MARK_LEARNED' "$ADBLOCK" || fail "нет persist VIDEO_AD_MARK hosts"
grep -q 'learnFromVideoAdMark' "$ADBLOCK" || fail "нет learnFromVideoAdMark"
grep -q 'VIDEO_AD_MARK_APPLIED' "$MAIN" || fail "mark video ad должен применять suppress"
grep -q 'auto-hide-clear' "$MAIN" || fail "нет auto-hide clear ad candidates"
grep -q 'blockAdFrame' "$MAIN" || fail "нет blockAdFrame для ad-iframe VIDEO до таймера"
grep -q 'auto-random-id' "$MAIN" || fail "нет pattern auto-hide random-id across refresh"
grep -q 'nGRXI' "$MANUAL" || fail "нет seeded nGRXI rule"
grep -q 'isBannerRandomId' "$MAIN" || fail "нет isBannerRandomId (маска баннеров)"
grep -qF '[0-9]{10,22}' "$MAIN" || fail "маска баннеров должна быть 5 букв + 10..22 цифр"
grep -q 'odPgP' "$MANUAL" || fail "нет seed odPgP"
grep -q 'nTgQB' "$MANUAL" || fail "нет seed nTgQB"
grep -q '__sidiAutoAdObs1321' "$MAIN" || fail "нет MutationObserver 1321"
grep -q 'alwaysOnAdPollRunnable' "$MAIN" || fail "нет always-on ad poll"
grep -q 'auto-close-popup' "$MAIN" || fail "нет close-popup auto-hide"
grep -q '__sidiAutoAdTick1321' "$MAIN" || fail "нет JS interval sweep"
grep -q obrut "$MAIN" || fail "obrut.show должен быть в playerUrl (Turbo)"
if grep -q 'iframe\[src\*=\"obrut' "$MANUAL"; then fail "нельзя сидить obrut iframe rule"; fi
grep -q '__sidiFramePicker1317' "$MAIN" || fail "frame picker не обновлён до 1317"
grep -q 'isAdFrameHost' "$MAIN" || fail "нет isAdFrameHost (узкий player-guard)"
grep -q 'moe.video' "$ADBLOCK" || fail "moe.video должен быть в ad creative hosts"
grep -q 'WebResourceResponse interceptKnownVideoAd' "$ADBLOCK" || fail "нет VAST neutralizer"
grep -q 'AD_VAST_NOFILL_OK' "$ADBLOCK" || fail "нет лога VAST neutralizer"
grep -q 'Access-Control-Allow-Credentials", "true"' "$ADBLOCK" || fail "нет credentialed CORS для VAST no-fill"
grep -q 'headers.put("Access-Control-Allow-Origin", origin)' "$ADBLOCK" || fail "VAST no-fill не отражает точный Origin"
if grep -q 'Access-Control-Allow-Origin", "\*"' "$ADBLOCK"; then fail "вернулся wildcard CORS"; fi
BLOCK_SECTION="$(sed -n '/private static boolean isExplicitVideoAdDescriptor/,/^    }/p' "$ADBLOCK")"
if printf '%s\n' "$BLOCK_SECTION" | grep -qE 'm3u8|mp4|mpd|mstream2inline|player_js|stravers'; then fail "neutralizer пытается блокировать bootstrap/main media"; fi
grep -q 'adBlocker.interceptKnownVideoAd(request)' "$MAIN" || fail "neutralizer не подключён"
[ "$(grep -c 'adBlocker.interceptKnownVideoAd(request)' "$MAIN")" -ge 2 ] || fail "neutralizer должен работать и для service worker, и player WebView"
if grep -q 'adBlocker.cleanPlayerPage' "$MAIN"; then fail "вернулся automatic DOM cleanup"; fi
grep -q 'setInitialScale(0)' "$MAIN" || fail "player WebView должен использовать auto initial scale"
grep -q 'setLoadWithOverviewMode(!searchOnly)' "$MAIN" || fail "нет overview mode для player WebView"
grep -q 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)' "$MAIN" || fail "нет desktop player UA"
grep -q "width=device-width, initial-scale=1, user-scalable=yes" "$MAIN" || fail "нет device-width viewport fallback"
grep -q 'PLAYER_DESKTOP_LAYOUT_136' "$MAIN" || fail "нет диагностики layout 13.4"
grep -q '__sidi_desktop_player_136' "$MAIN" || fail "нет player layout injection 13.4"
grep -q 'moviead55|buzzoola|vqserve' "$MAIN" || fail "player layout не исключает рекламные iframe"
grep -q '__sidiPlayerAutoScrolled136' "$MAIN" || fail "нет автопрокрутки к плееру"
grep -q 'PICKER_INSTALL' "$MAIN" || fail "нет диагностики установки picker overlay"
grep -q 'private static final int SCHEMA = 139' "$MANUAL" || fail "manual ad schema не обновлена"
grep -q 'final String href' "$MANUAL" || fail "manual rule не сохраняет href"
grep -q 'final String text' "$MANUAL" || fail "manual rule не сохраняет text"
grep -q 'data-sidi-picker-token' "$MAIN" || fail "picker не хранит точный выбранный DOM node"
grep -q 'FRAME_PICKER_DOCUMENT_START' "$MAIN" || fail "нет picker внутри cross-origin iframe"
grep -q 'public int decision(String token)' "$MAIN" || fail "нет подтверждения удаления для frame picker"
grep -q 'public String rulesForHost(String host)' "$MAIN" || fail "сохранённые ad-rules не применяются внутри iframe"
grep -q 'data-sidi-manual-rule' "$MAIN" || fail "нет rule id для undo"
grep -q '__sidi_ad_picker_overlay_133' "$MAIN" || fail "нет capture overlay для ad picker"
grep -q 'Этот элемент нельзя блокировать: он может быть частью плеера' "$MAIN" || fail "нет защиты player media в picker"
grep -q 'VIDEO_AD_MARK_BEGIN' "$MAIN" || fail "нет video-ad marker"
grep -q 'VIDEO_AD_MARK_END' "$MAIN" || fail "нет video-ad marker end"
grep -q 'RULE_SS = "builtin_ss"' "$RULES" || fail "нет kino → ss"
grep -q 'RULE_KINO_WIN = "builtin_kino_win"' "$RULES" || fail "нет poisk.ru → kino.win"
grep -q 'interactionShield.setClickable(false)' "$MAIN" || fail "loading shield clickable"
grep -q 'onPageCommitVisible' "$MAIN" || fail "нет onPageCommitVisible"
grep -q 'MEDIA_SYNTHETIC_DUPLICATE_WINDOW_MS = 1200L' "$MAIN" || fail "нет Button Mapper duplicate window"
if grep -R -q 'new KeyEvent' "$PROJECT_DIR/app/src/main/java"; then fail "найден synthetic KeyEvent"; fi
if grep -R -q 'MotionEvent.obtain' "$PROJECT_DIR/app/src/main/java"; then fail "найден synthetic touch"; fi
grep -q 'enterNativeFullScreen(view, callback, tab);' "$MAIN" || fail "нет native Chromium fullscreen"
grep -q 'PointerIcon.TYPE_ARROW' "$HOST" || fail "fullscreen cursor не системная стрелка"
if grep -R -qE 'org\.adblockplus\.android|localhost:2020|androidx\.work|WorkManager|MediaSession' "$PROJECT_DIR/app/src/main/java" "$GRADLE"; then fail "вернулся запрещённый legacy компонент"; fi
bash -n "$PROJECT_DIR/build.sh"
bash -n "$PROJECT_DIR/install-to-tv.sh"
bash -n "$PROJECT_DIR/publish-13.11-github-only.sh"
bash -n "$PROJECT_DIR/smoke-test-13.11.sh"

if grep -q '__sidiKnownAdObserver' "$MAIN"; then fail "persistent known-ad MutationObserver запрещён"; fi
grep -q "#movie_video','div.topAdPad','#tgWrapper" "$MAIN" || fail "нет постоянного удаления подтверждённых рекламных блоков"
grep -q 'POPUP_WINDOW_BLOCKED' "$MAIN" || fail "нет блокировки рекламных popup"
grep -q 'isKnownAdNavigation' "$ADBLOCK" || fail "нет классификатора рекламных popup"
grep -q 'viewportW-menuW-16' "$MAIN" || fail "player/menu не рассчитываются по реальной ширине viewport"
grep -q "menu.style.setProperty('width',menuW+'px'" "$MAIN" || fail "source menu не вписывается в viewport"
grep -q '__sidiPlayerAutoScrolled136' "$MAIN" || fail "нет автопрокрутки к плееру 13.4"
grep -q '__sidiManualRuleObserver1310' "$MAIN" || fail "нет узкого observer для повторно создаваемых сохранённых ad-rules"
if grep -q 'interceptKnownDisplayAd' "$MAIN" "$ADBLOCK"; then fail "display-ad network substitution вернулась"; fi
grep -q 'setWebContentsDebuggingEnabled(false)' "$MAIN" || fail "WebView debugging должен быть выключен"
grep -q 'setOffscreenPreRaster(false)' "$MAIN" || fail "offscreen pre-raster должен быть выключен"
grep -q 'setSupportMultipleWindows(false)' "$MAIN" || fail "multiple windows должны быть выключены"
grep -q 'setJavaScriptCanOpenWindowsAutomatically(false)' "$MAIN" || fail "window.open должен быть выключен"
grep -q 'POPUP_WINDOW_BLOCKED' "$MAIN" || fail "нет жёсткой блокировки popup WebView"
grep -q 'tab.hibernate()' "$MAIN" || fail "неактивные player WebView не выгружаются"
grep -q 'MAIN_MEDIA_FIRST' "$MAIN" || fail "нет однократной диагностики main media"
if grep -q 'AD_CANDIDATE_ALLOWED' "$ADBLOCK"; then fail "вернулось логирование каждого ad request"; fi

if grep -q 'installDesktopBrowserIdentity(web);' "$MAIN"; then fail "navigator spoof включён; нужен только native Windows Chrome UA как в Via"; fi
grep -q 'AD_MAIN_FRAME_BLOCKED' "$MAIN" || fail "нет блокировки ухода player-tab на рекламный сайт"
grep -q '__sidi_manual_css_1310' "$MAIN" || fail "manual ad rule не закрепляется CSS-правилом"
if grep -q "if(e.querySelector('video,audio'))return true" "$MAIN"; then fail "ad popup с video снова ошибочно защищается как основной player"; fi
grep -q 'PICKER_DEFER_TO_FRAME' "$MAIN" || fail "picker не передаёт клик во внутренний player frame"

grep -q 'function visualAt(x,y,raw)' "$MAIN" || fail "нет визуального hit-test для pointer-events:none баннера"
grep -q 'PICKER_CANDIDATE' "$MAIN" || fail "нет диагностики выбранного визуального рекламного слоя"
grep -q 'adPickerPromptOpen' "$MAIN" || fail "нет защиты от двойного dialog picker"
grep -q 'Режим выбора остаётся включён' "$MAIN" || fail "picker выключается после одного удаления"
grep -q 'PlayerChoiceBridge' "$MAIN" || fail "нет сохранения выбранного плеера"
grep -q 'PLAYER_CHOICE_SAVED' "$MAIN" || fail "нет лога сохранения выбранного плеера"
grep -q 'PLAYER_CHOICE_RESTORE' "$MAIN" || fail "нет восстановления выбранного плеера"
grep -q 'playerIndex' "$PROJECT_DIR/app/src/main/java/com/kinotv/app/MovieRecord.java" || fail "playerIndex не хранится в MovieRecord"
grep -q 'playerLabel' "$PROJECT_DIR/app/src/main/java/com/kinotv/app/MovieRecord.java" || fail "playerLabel не хранится в MovieRecord"
echo "Статическая проверка исходников 13.11 пройдена."
